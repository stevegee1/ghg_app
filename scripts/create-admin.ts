import 'dotenv/config';
import { PrismaClient, PortalRole } from '@prisma/client';
import * as bcrypt from 'bcrypt';
import * as crypto from 'crypto';

const prisma = new PrismaClient();

function validatePasswordPolicy(password: string): { valid: boolean; reason?: string } {
  if (password.length < 14) {
    return { valid: false, reason: 'Password must be at least 14 characters long (NIST SP 800-63B standard).' };
  }
  if (!/[A-Z]/.test(password)) {
    return { valid: false, reason: 'Password must include at least one uppercase letter.' };
  }
  if (!/[a-z]/.test(password)) {
    return { valid: false, reason: 'Password must include at least one lowercase letter.' };
  }
  if (!/[0-9]/.test(password)) {
    return { valid: false, reason: 'Password must include at least one number.' };
  }
  if (!/[!@#$%^&*()_+\-=\[\]{};':"\\|,.<>\/?]/.test(password)) {
    return { valid: false, reason: 'Password must include at least one special character symbol.' };
  }
  return { valid: true };
}

function generateEnterpriseSecret(): string {
  // 18 bytes base64url = 24 alphanumeric characters + compliant suffix for complexity guarantee
  return crypto.randomBytes(18).toString('base64url') + '!A9';
}

async function main() {
  const args = process.argv.slice(2);
  const email = args[0] || process.env.ADMIN_EMAIL;

  if (!email) {
    console.error('═══════════════════════════════════════════════════════════════════════');
    console.error('ERROR: Admin email is required.');
    console.error('Usage:   npm run create-admin <email> [optional_strong_password]');
    console.error('Example: npm run create-admin admin@myorganization.com');
    console.error('═══════════════════════════════════════════════════════════════════════');
    process.exit(1);
  }

  let password = args[1] || process.env.ADMIN_PASSWORD;
  let autoGenerated = false;

  if (!password) {
    password = generateEnterpriseSecret();
    autoGenerated = true;
  } else {
    const policy = validatePasswordPolicy(password);
    if (!policy.valid) {
      console.error('═══════════════════════════════════════════════════════════════════════');
      console.error(`SECURITY POLICY ERROR: ${policy.reason}`);
      console.error('═══════════════════════════════════════════════════════════════════════');
      process.exit(1);
    }
  }

  console.log(`Setting up Google SaaS standard administrator for: ${email}`);

  // Salt rounds: 12 in production, 10 in dev
  const saltRounds = process.env.NODE_ENV === 'production' ? 12 : 10;
  const passwordHash = await bcrypt.hash(password, saltRounds);
  const adminId = `usr_admin_${Date.now()}`;

  const user = await prisma.portalUser.upsert({
    where: { email },
    update: {
      passwordHash,
      role: PortalRole.ADMIN,
    },
    create: {
      id: adminId,
      email,
      passwordHash,
      role: PortalRole.ADMIN,
    },
  });

  console.log('═══════════════════════════════════════════════════════════════════════');
  console.log('✅ Enterprise Administrator Account Provisioned:');
  console.log(`   User ID:   ${user.id}`);
  console.log(`   Email:     ${user.email}`);
  console.log(`   Role:      ${user.role}`);
  if (autoGenerated) {
    console.log(`   Generated Password: ${password}`);
    console.log('   Notice:    Save this credential securely. It will not be shown again.');
  } else {
    console.log('   Password:  [Validated against NIST SP 800-63B standards]');
  }
  console.log('═══════════════════════════════════════════════════════════════════════');
}

main()
  .catch((err) => {
    console.error('Failed to provision admin account:', err);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
